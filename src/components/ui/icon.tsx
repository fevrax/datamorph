export function Icon({
  icon,
  width = 16,
  height,
  ...props
}: Omit<LucideProps, "size"> & {
  icon: string;
  width?: number | string;
  height?: number | string;
}) {
  const Component =
    rules.find(([pattern]) => pattern.test(icon))?.[1] || Terminal;
  return (
    <Component
      {...props}
      width={width}
      height={height || width}
      strokeWidth={1.7}
      aria-hidden={props["aria-label"] ? undefined : true}
    />
  );
}
